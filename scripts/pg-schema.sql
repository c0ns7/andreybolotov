  slug TEXT NOT NULL UNIQUE,
  label TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS blog_post_tags (
  post_id BIGINT NOT NULL REFERENCES blog_posts(id) ON DELETE CASCADE,
