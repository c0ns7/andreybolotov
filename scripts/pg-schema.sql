CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  email TEXT,
  locality TEXT,
  password_hash TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user',
  blocked INTEGER NOT NULL DEFAULT 0,
  email_notify_chat INTEGER NOT NULL DEFAULT 1,
  email_notify_raffles INTEGER NOT NULL DEFAULT 1,
  chat_unread_email_last_at BIGINT,
  email_notify_raffle_orders INTEGER NOT NULL DEFAULT 1,
  last_active_at BIGINT
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
  ON users (LOWER(email))
  WHERE email IS NOT NULL AND LENGTH(TRIM(email)) > 0;

CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

CREATE TABLE IF NOT EXISTS support_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body TEXT NOT NULL,
  is_staff INTEGER NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  read_by_staff_at BIGINT,
  read_by_user_at BIGINT,
  attachment_url TEXT,
  attachment_name TEXT,
  attachment_mime TEXT
);
CREATE INDEX IF NOT EXISTS idx_support_user ON support_messages(user_id, created_at);

CREATE TABLE IF NOT EXISTS raffles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_hash TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  cover_image_url TEXT NOT NULL DEFAULT '',
  price_rub INTEGER NOT NULL DEFAULT 0,
  cenopad_enabled INTEGER NOT NULL DEFAULT 0,
  cenopad_price_rub INTEGER NOT NULL DEFAULT 0,
  cenopad_start_at BIGINT,
  cenopad_end_at BIGINT,
  old_price_rub INTEGER NOT NULL DEFAULT 0,
  ticket_count INTEGER NOT NULL DEFAULT 0,
  collection_url TEXT NOT NULL DEFAULT '',
  tbank_collection_url TEXT NOT NULL DEFAULT '',
  collection_recipient TEXT NOT NULL DEFAULT '',
  sber_collection_recipient TEXT NOT NULL DEFAULT '',
  tbank_collection_recipient TEXT NOT NULL DEFAULT '',
  qr_image_url TEXT NOT NULL DEFAULT '',
  qr_recipient TEXT NOT NULL DEFAULT '',
  qr_payment_purpose TEXT NOT NULL DEFAULT 'Оплата услуг',
  sber_enabled INTEGER NOT NULL DEFAULT 1,
  tbank_enabled INTEGER NOT NULL DEFAULT 0,
  qr_enabled INTEGER NOT NULL DEFAULT 1,
  rules_url TEXT NOT NULL DEFAULT '',
  live_stream_note TEXT NOT NULL DEFAULT '',
  live_stream_url TEXT NOT NULL DEFAULT '',
  live_stream_at BIGINT,
  live_stream_status TEXT NOT NULL DEFAULT 'scheduled',
  status TEXT NOT NULL DEFAULT 'active',
  sort_order INTEGER NOT NULL DEFAULT 0,
  wholesale_enabled INTEGER NOT NULL DEFAULT 0,
  promo_5_plus_1_enabled INTEGER NOT NULL DEFAULT 0,
  promo_5_plus_1_locked_free_count INTEGER NOT NULL DEFAULT 0,
  hidden_from_public INTEGER NOT NULL DEFAULT 0,
  launch_notify_sent_at BIGINT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_raffles_sort ON raffles(sort_order, id DESC);

CREATE TABLE IF NOT EXISTS raffle_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id BIGINT NOT NULL REFERENCES raffles(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  bank TEXT,
  amount_rub INTEGER NOT NULL,
  ticket_count INTEGER NOT NULL,
  cenopad_applied INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL,
  reserved_until BIGINT NOT NULL,
  reserve_extended_once INTEGER NOT NULL DEFAULT 0,
  reserve_reminder_sent_at BIGINT,
  receipt_url TEXT,
  receipt_name TEXT,
  receipt_mime TEXT,
  receipt_reject_count INTEGER NOT NULL DEFAULT 0,
  last_reject_comment TEXT,
  public_status_token TEXT UNIQUE,
  receipt_sha256 TEXT,
  receipt_same_as_previous INTEGER NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ro_raffle ON raffle_orders(raffle_id);
CREATE INDEX IF NOT EXISTS idx_ro_user ON raffle_orders(user_id);
CREATE INDEX IF NOT EXISTS idx_ro_status ON raffle_orders(status);

CREATE TABLE IF NOT EXISTS raffle_ticket_holds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id BIGINT NOT NULL REFERENCES raffles(id) ON DELETE CASCADE,
  order_id BIGINT NOT NULL REFERENCES raffle_orders(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  ticket_number INTEGER NOT NULL,
  is_bonus INTEGER NOT NULL DEFAULT 0,
  hold_status TEXT NOT NULL,
  expires_at BIGINT,
  created_at BIGINT NOT NULL,
  UNIQUE (raffle_id, ticket_number)
);
CREATE INDEX IF NOT EXISTS idx_rth_raffle ON raffle_ticket_holds(raffle_id);
CREATE INDEX IF NOT EXISTS idx_rth_order ON raffle_ticket_holds(order_id);

CREATE TABLE IF NOT EXISTS raffle_order_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES raffle_orders(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  detail TEXT,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_roe_order ON raffle_order_events(order_id);

CREATE TABLE IF NOT EXISTS used_receipts (
  sha256 TEXT PRIMARY KEY,
  first_order_id BIGINT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_used_receipts_created_at ON used_receipts(created_at);

CREATE TABLE IF NOT EXISTS site_settings (
  id INTEGER PRIMARY KEY,
  maintenance_enabled INTEGER NOT NULL DEFAULT 0
);
INSERT INTO site_settings (id, maintenance_enabled)
VALUES (1, 0)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS raffle_wholesale_assignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id BIGINT NOT NULL REFERENCES raffles(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  user_slot_index INTEGER NOT NULL,
  wholesale_number INTEGER NOT NULL,
  created_at BIGINT NOT NULL,
  UNIQUE (raffle_id, user_id, user_slot_index),
  UNIQUE (raffle_id, wholesale_number)
);
CREATE INDEX IF NOT EXISTS idx_rwa_raffle ON raffle_wholesale_assignments(raffle_id);

CREATE TABLE IF NOT EXISTS raffle_phone_preassignments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raffle_id BIGINT NOT NULL REFERENCES raffles(id) ON DELETE CASCADE,
  ticket_number INTEGER NOT NULL,
  phone TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  UNIQUE (raffle_id, ticket_number)
);
CREATE INDEX IF NOT EXISTS idx_rpp_raffle_phone ON raffle_phone_preassignments(raffle_id, phone);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at BIGINT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_prt_user ON password_reset_tokens(user_id);
CREATE INDEX IF NOT EXISTS idx_prt_expires ON password_reset_tokens(expires_at);
